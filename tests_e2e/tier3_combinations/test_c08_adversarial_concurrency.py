    def test_adv_01_sorted_lock_acquisition_order_and_sql(self):
        """
        Adversarial Test 1: Verify that Insumos are locked in strictly ascending ID order.
        Even if recipes are defined and ordered in reverse or arbitrary order.
        Inspects both DB state and SQL query to prove .order_by('id') is enforced.
        """
        ins_c = self.Insumo.objects.create(codigo="INS-C", nombre="Insumo C", unidad_medida="kg", stock_actual=Decimal("10.000"), stock_minimo=Decimal("1.000"))
        ins_a = self.Insumo.objects.create(codigo="INS-A", nombre="Insumo A", unidad_medida="kg", stock_actual=Decimal("10.000"), stock_minimo=Decimal("1.000"))
        ins_b = self.Insumo.objects.create(codigo="INS-B", nombre="Insumo B", unidad_medida="kg", stock_actual=Decimal("10.000"), stock_minimo=Decimal("1.000"))

        ids = [ins_c.id, ins_a.id, ins_b.id]
        sorted_ids = sorted(ids)

        p_reverse = self.Plato.objects.create(nombre="Plato Reverse", valor=5000)
        # Add recipes in reverse ID order
        for i_id in reversed(sorted_ids):
            ins_obj = self.Insumo.objects.get(id=i_id)
            self.RecetaItem.objects.create(plato=p_reverse, insumo=ins_obj, cantidad=Decimal("0.500"))

        orden = self.Orden.objects.create(cliente="Adversarial Lock Order", canal_venta="Local", tipo_pago="Efectivo")
        self.OrdenItem.objects.create(orden=orden, plato=p_reverse, cantidad=1)

        # Verify SQL query generated by Insumo.objects.filter(...).select_for_update().order_by("id")
        qs = self.Insumo.objects.filter(id__in=ids).select_for_update().order_by("id")
        sql_str = str(qs.query).upper()
        self.assertIn('ORDER BY', sql_str, "Query must include ORDER BY to guarantee total ordering for deadlock prevention")
        self.assertIn('"ID" ASC', sql_str, "Lock order must be ascending primary key order")

        # Execute deduction
        res = self.descontar_stock_orden(orden.id)
        self.assertTrue(res.get("success"), "Deduction must succeed")

        movs = list(self.MovimientoStock.objects.filter(orden=orden).order_by("id"))
        self.assertEqual(len(movs), 3)

        for i_id in sorted_ids:
            ins = self.Insumo.objects.get(id=i_id)
            self.assertEqual(ins.stock_actual, Decimal("9.500"))

    def test_adv_02_rapid_fire_idempotency_no_double_deduction(self):
        """
        Adversarial Test 2: Rapid sequential calls to descontar_stock_orden on the same order.
        Simulates cashiers double-clicking confirm or network retries.
        Expected: First call executes; subsequent calls are strictly idempotent with 0 movements.
        """
        ins = self.Insumo.objects.create(
            codigo="INS-RAPID", nombre="Carne Rapid", unidad_medida="kg",
            stock_actual=Decimal("20.000"), stock_minimo=Decimal("2.000"), costo_unitario=Decimal("5000.000")
        )
        p = self.Plato.objects.create(nombre="Lomo Rapid", valor=6000)
        self.RecetaItem.objects.create(plato=p, insumo=ins, cantidad=Decimal("0.500"))

        orden = self.Orden.objects.create(cliente="Mesa Rapid Call", canal_venta="Local", tipo_pago="Efectivo")
        self.OrdenItem.objects.create(orden=orden, plato=p, cantidad=2)  # Demands 1.000 kg total

        # Fire 5 consecutive deduction calls
        results = [self.descontar_stock_orden(orden.id) for _ in range(5)]

        # Verify first call executed
        self.assertTrue(results[0].get("success"))
        self.assertEqual(results[0].get("movimientos"), 1)
        self.assertFalse(results[0].get("idempotente", False))

        # Verify calls 2-5 were idempotent
        for idx, r in enumerate(results[1:], start=2):
            self.assertTrue(r.get("success"), f"Call {idx} must succeed idempotently")
            self.assertTrue(r.get("idempotente"), f"Call {idx} must have idempotent=True")
            self.assertEqual(r.get("movimientos"), 0, f"Call {idx} must generate 0 movements")

        # Verify stock was deducted EXACTLY ONCE: 20.000 - 1.000 = 19.000
        ins.refresh_from_db()
        self.assertEqual(ins.stock_actual, Decimal("19.000"), "Stock must be deducted exactly once")

        # Verify Kardex has EXACTLY ONE movement
        kardex_count = self.MovimientoStock.objects.filter(orden=orden).count()
        self.assertEqual(kardex_count, 1, "Exactly one Kardex movement must exist")

