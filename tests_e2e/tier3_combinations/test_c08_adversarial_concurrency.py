    def test_adv_04_zero_and_negative_stock_quiebre_alerts(self):
        """
        Adversarial Test 4: Verify stock alert logic when stock crosses into negative / quiebre territory.
        """
        ins1 = self.Insumo.objects.create(codigo="ADV-AL1", nombre="Harina Alerta", unidad_medida="kg", stock_actual=Decimal("5.000"), stock_minimo=Decimal("4.000"))
        ins2 = self.Insumo.objects.create(codigo="ADV-AL2", nombre="Azúcar Alerta", unidad_medida="kg", stock_actual=Decimal("5.000"), stock_minimo=Decimal("2.000"))
        ins3 = self.Insumo.objects.create(codigo="ADV-AL3", nombre="Levadura Quiebre", unidad_medida="kg", stock_actual=Decimal("1.000"), stock_minimo=Decimal("0.000"))
        ins4 = self.Insumo.objects.create(codigo="ADV-AL4", nombre="Sal Segura", unidad_medida="kg", stock_actual=Decimal("10.000"), stock_minimo=Decimal("2.000"))

        p = self.Plato.objects.create(nombre="Plato Alertas", valor=4000)
        self.RecetaItem.objects.create(plato=p, insumo=ins1, cantidad=Decimal("2.000"))
        self.RecetaItem.objects.create(plato=p, insumo=ins2, cantidad=Decimal("3.000"))
        self.RecetaItem.objects.create(plato=p, insumo=ins3, cantidad=Decimal("2.000"))
        self.RecetaItem.objects.create(plato=p, insumo=ins4, cantidad=Decimal("2.000"))

        orden = self.Orden.objects.create(cliente="Mesa Alertas Test", canal_venta="Local", tipo_pago="Efectivo")
        self.OrdenItem.objects.create(orden=orden, plato=p, cantidad=1)

        res = self.descontar_stock_orden(orden.id)
        self.assertTrue(res.get("success"))

        alertas = res.get("alertas_stock_minimo", [])
        alert_codigos = [a["codigo"] for a in alertas]

        self.assertIn("ADV-AL1", alert_codigos, "Stock below minimum must trigger alert")
        self.assertIn("ADV-AL2", alert_codigos, "Stock equal to minimum must trigger alert")
        self.assertIn("ADV-AL3", alert_codigos, "Negative stock must trigger alert")
        self.assertNotIn("ADV-AL4", alert_codigos, "Stock above minimum must NOT trigger alert")

        quiebre_alert = [a for a in alertas if a["codigo"] == "ADV-AL3"][0]
        self.assertTrue(quiebre_alert["es_quiebre_negativo"], "ADV-AL3 must have es_quiebre_negativo=True")

    def test_adv_05_deleted_and_empty_orders_handling(self):
        """
        Adversarial Test 5: Handling of deleted orders, empty orders, and nonexistent orders.
        """
        ins = self.Insumo.objects.create(codigo="ADV-DEL", nombre="Insumo Del", unidad_medida="kg", stock_actual=Decimal("10.000"))
        p = self.Plato.objects.create(nombre="Plato Del", valor=2000)
        self.RecetaItem.objects.create(plato=p, insumo=ins, cantidad=Decimal("1.000"))

        # Case A: Deleted order
        orden_del = self.Orden.objects.create(cliente="Cliente Del", canal_venta="Local", tipo_pago="Efectivo", estado=Orden.ESTADO_ELIMINADA)
        self.OrdenItem.objects.create(orden=orden_del, plato=p, cantidad=1)

        res_del = self.descontar_stock_orden(orden_del.id)
        self.assertFalse(res_del.get("success"), "Deleted order must not be deducted")
        ins.refresh_from_db()
        self.assertEqual(ins.stock_actual, Decimal("10.000"), "Stock must remain unchanged for deleted order")

        # Case B: Non-existent order
        res_none = self.descontar_stock_orden(-1)
        self.assertFalse(res_none.get("success"), "Non-existent order must return success=False")

        # Case C: Empty order (no items)
        orden_empty = self.Orden.objects.create(cliente="Cliente Empty", canal_venta="Local", tipo_pago="Efectivo")
        res_empty = self.descontar_stock_orden(orden_empty.id)
        self.assertTrue(res_empty.get("success"), "Empty order should succeed safely")
        self.assertEqual(res_empty.get("movimientos"), 0)
        orden_empty.refresh_from_db()
        self.assertTrue(orden_empty.stock_descontado, "Empty order should be marked stock_descontado=True")

    def test_adv_06_confirmar_orden_view_hook_stock_descontado_field(self):
        """
        Adversarial Test 6: Verify the returned JSON payload of confirmar_orden view hook.
        Detects if stock_descontado in the returned JSON accurately reflects True after successful deduction.
        """
        ins = self.Insumo.objects.create(codigo="ADV-VIEW", nombre="Insumo View", unidad_medida="kg", stock_actual=Decimal("10.000"))
        p = self.Plato.objects.create(nombre="Plato View", valor=3000)
        self.RecetaItem.objects.create(plato=p, insumo=ins, cantidad=Decimal("1.000"))

        orden = self.Orden.objects.create(cliente="Mesa View Hook", canal_venta="Local", tipo_pago="Efectivo")
        self.OrdenItem.objects.create(orden=orden, plato=p, cantidad=1)

        client = self.get_client()
        resp = client.post(f"/pedidos/{orden.id}/confirmar/", data=json.dumps({"tipo_pago": "Efectivo"}), content_type="application/json")
        self.assertEqual(resp.status_code, 200)

        data = resp.json()
        self.assertTrue(data.get("success"))

        # Verify DB state
        orden.refresh_from_db()
        self.assertTrue(orden.stock_descontado, "DB state of stock_descontado must be True")

        # Inspect the JSON returned to caller
        # Note: If confirmar_orden does not refresh the in-memory model instance after calling descontar_stock_orden,
        # data["stock_descontado"] will be False!
        json_stock_descontado = data.get("stock_descontado")
        self.assertTrue(
            json_stock_descontado,
            f"Adversarial Finding: confirmar_orden JSON returned 'stock_descontado': {json_stock_descontado}, but DB has {orden.stock_descontado}. View did not refresh model in memory!"
        )
